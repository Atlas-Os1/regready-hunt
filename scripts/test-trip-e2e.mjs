import puppeteer from "puppeteer";
const base = process.env.REGREADY_URL || "https://regready-hunt-production.srvcflo.workers.dev";
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const browser = await puppeteer.launch({ headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
const email = `trip.${Date.now()}@example.com`;
const password = "TripPlanner!2026";
await page.setViewport({ width: 390, height: 844, isMobile: true });
await page.goto(`${base}/`, { waitUntil: "networkidle2" });
await page.type("#account-email", email); await page.type("#account-password", password); await page.click("button[data-mode=signup]");
await page.waitForFunction(() => document.querySelector("#account-state")?.textContent?.includes("Signed in"));
await page.goto(`${base}/trips.html`, { waitUntil: "networkidle2" });
await page.type("#trip-title", "Northwest Oklahoma October opener"); await page.select("#trip-state", "Oklahoma"); await page.type("#trip-region", "Northwest Oklahoma"); await page.select("#trip-species", "White-tailed deer"); await page.type("#trip-start", "2026-10-03"); await page.type("#trip-end", "2026-10-05");
await Promise.all([page.waitForNavigation({ waitUntil: "networkidle2" }), page.click("#trip-form button[type=submit]")]);
if (!page.url().match(/\/trip(?:\.html)?\?id=/)) throw new Error(`trip navigation failed: ${page.url()}`);
await page.waitForSelector(".record-card");
const itemCount = await page.$$eval("#trip-items .record-card", (nodes) => nodes.length);
if (itemCount !== 6) throw new Error(`expected 6 plan lanes, got ${itemCount}`);
await page.type("#invite-name", "Alex"); await page.type("#invite-email", "alex@example.com"); await page.click("#invite-form button[type=submit]");
await page.waitForFunction(() => document.querySelector("#invite-message")?.textContent?.includes("/trip.html?share="));
const shareText = await page.$eval("#invite-message", (el) => el.textContent);
const shareUrl = shareText.match(/https?:\/\/[^ ]+\/trip\.html\?share=[^ ]+/)?.[0];
if (!shareUrl) throw new Error(`share URL missing: ${shareText}`);
const shared = await browser.newPage(); await shared.setViewport({ width: 390, height: 844, isMobile: true }); await shared.goto(shareUrl, { waitUntil: "networkidle2" });
const sharedAccess = await shared.$eval("#trip-access", (el) => el.textContent); const sharedItems = await shared.$$eval("#trip-items .record-card", (nodes) => nodes.length);
if (!sharedAccess.includes("Shared read-only") || sharedItems !== 6) throw new Error(`shared view failed: ${sharedAccess}, ${sharedItems}`);
await page.goto(`${base}/connections.html`, { waitUntil: "networkidle2" });
const cards = await page.$$eval(".connection-grid .account-card", (nodes) => nodes.length); const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
if (cards !== 4 || overflow) throw new Error(`connections check failed: cards=${cards}, overflow=${overflow}`);
console.log(JSON.stringify({ email, itemCount, sharedAccess, sharedItems, connectionCards: cards, overflow }));
await browser.close();
